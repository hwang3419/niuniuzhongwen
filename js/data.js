// 工具函数：获取所有字卡平铺列表
function getAllCharacters() {
  const list = [];
  MLP_DATABASE.units.forEach(unit => {
    unit.characters.forEach(c => {
      list.push({ ...c, unitId: unit.id, unitTitle: unit.title });
    });
  });
  return list;
}

// 获取某个字卡
function getCharacterByChar(charStr) {
  for (const unit of MLP_DATABASE.units) {
    const found = unit.characters.find(c => c.char === charStr);
    if (found) {
      return { ...found, unitId: unit.id, unitTitle: unit.title };
    }
  }
  return null;
}

